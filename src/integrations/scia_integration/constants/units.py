"""
Unit conversion constants for SCIA integration.

These constants define conversion factors between different unit systems
used in SCIA results processing and display.
"""

# Force and moment conversions
N_TO_KN = 1 / 1000.0  # Newton to kilonewton
NM_TO_KNM = 1 / 1000.0  # Newton-meter to kilonewton-meter
NMM_TO_KNM = 1 / 1000000.0  # Newton-millimeter to kilonewton-meter

# Length conversions
MM_TO_M = 1 / 1000.0  # Millimeter to meter
M_TO_MM = 1000.0  # Meter to millimeter

# Load density conversions
KN_PER_SQM_TO_N_PER_SQM = 1000.0  # kN/m² to N/m²
KN_PER_M_TO_N_PER_M = 1000.0  # kN/m to N/m
